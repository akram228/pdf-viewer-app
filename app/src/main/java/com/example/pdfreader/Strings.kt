/** Supported app languages. The order here MUST match the order of the texts in [STR]. */
enum class AppLang(val code: String, val native: String, val rtl: Boolean) {
    EN("en", "English", false),
    MY("my", "မြန်မာ", false),
    AR("ar", "العربية", true),
    UR("ur", "اردو", true),
    HI("hi", "हिन्दी", false),
    ZH("zh", "中文", false),
    JA("ja", "日本語", false),
    KO("ko", "한국어", false),
    TH("th", "ไทย", false);

    companion object {
        fun fromCode(code: String?): AppLang =
            values().firstOrNull { it.code == code } ?: EN

        /** First launch: use the phone's language if we support it, otherwise English. */
        fun fromSystem(): AppLang = fromCode(Locale.getDefault().language)
    }
}

/** Current language. It is Compose state, so changing it redraws the whole UI. */
object Loc {
    var lang by mutableStateOf(AppLang.EN)
}

/** Translate [key] into the current language; {0}, {1}… are replaced by [args]. */
fun tr(key: String, vararg args: Any?): String {
    val row = STR[key] ?: return key
    var s = row.getOrNull(Loc.lang.ordinal)?.takeIf { it.isNotEmpty() } ?: row[0]
    args.forEachIndexed { i, v -> s = s.replace("{" + i + "}", v.toString()) }
    return s
}

